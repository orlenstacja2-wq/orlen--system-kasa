import { sql } from 'drizzle-orm'
import {
  boolean,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  serial,
  text,
  timestamp,
  uniqueIndex,
} from 'drizzle-orm/pg-core'

/** Station staff. Role decides access: pracownik < kierownik < admin. */
export const employees = pgTable('employees', {
  id: serial().primaryKey(),
  /** Employee number typed on the login screen. */
  login: text().notNull().unique(),
  name: text().notNull(),
  role: text().notNull().default('pracownik'),
  pinHash: text('pin_hash').notNull(),
  active: boolean().notNull().default(true),
  failedAttempts: integer('failed_attempts').notNull().default(0),
  lockedUntil: timestamp('locked_until', { withTimezone: true }),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

/** Login sessions. `id` is the SHA-256 of the cookie token, never the token itself. */
export const sessions = pgTable('sessions', {
  id: text().primaryKey(),
  employeeId: integer('employee_id')
    .notNull()
    .references(() => employees.id),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
})

/** Cash registers (kasy / stanowiska) at the station. */
export const registers = pgTable('registers', {
  id: serial().primaryKey(),
  code: text().notNull().unique(),
  name: text().notNull(),
  active: boolean().notNull().default(true),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

export const shifts = pgTable(
  'shifts',
  {
    id: serial().primaryKey(),
    employeeId: integer('employee_id')
      .notNull()
      .references(() => employees.id),
    registerId: integer('register_id')
      .notNull()
      .references(() => registers.id),
    status: text().notNull().default('open'),
    startedAt: timestamp('started_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
    endedAt: timestamp('ended_at', { withTimezone: true }),
    openingNote: text('opening_note'),
    closingNote: text('closing_note'),
  },
  (t) => [
    // One open shift per employee and per register.
    uniqueIndex('shifts_open_employee_idx')
      .on(t.employeeId)
      .where(sql`status = 'open'`),
    uniqueIndex('shifts_open_register_idx')
      .on(t.registerId)
      .where(sql`status = 'open'`),
    index('shifts_started_idx').on(t.startedAt),
  ],
)

/** Controlled register changes during a shift, approved by a manager. */
export const registerChanges = pgTable('register_changes', {
  id: serial().primaryKey(),
  shiftId: integer('shift_id')
    .notNull()
    .references(() => shifts.id),
  fromRegisterId: integer('from_register_id')
    .notNull()
    .references(() => registers.id),
  toRegisterId: integer('to_register_id')
    .notNull()
    .references(() => registers.id),
  reason: text().notNull(),
  approvedBy: integer('approved_by')
    .notNull()
    .references(() => employees.id),
  changedAt: timestamp('changed_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

/** Recorded fills. Prices and promotions are copied in, so later edits never change history. */
export const fuelings = pgTable(
  'fuelings',
  {
    id: serial().primaryKey(),
    /** Generated by the register per settlement; blocks double saving. */
    clientRef: text('client_ref').notNull().unique(),
    shiftId: integer('shift_id')
      .notNull()
      .references(() => shifts.id),
    registerId: integer('register_id')
      .notNull()
      .references(() => registers.id),
    employeeId: integer('employee_id')
      .notNull()
      .references(() => employees.id),
    docNumber: text('doc_number').notNull().unique(),
    docType: text('doc_type').notNull(),
    pump: integer().notNull(),
    fuelId: text('fuel_id').notNull(),
    fuelName: text('fuel_name').notNull(),
    liters: numeric({ precision: 10, scale: 2 }).notNull(),
    pricePerLiter: numeric('price_per_liter', {
      precision: 10,
      scale: 3,
    }).notNull(),
    grossAmount: numeric('gross_amount', { precision: 12, scale: 2 }).notNull(),
    discountAmount: numeric('discount_amount', { precision: 12, scale: 2 })
      .notNull()
      .default('0'),
    amount: numeric({ precision: 12, scale: 2 }).notNull(),
    promotionId: integer('promotion_id').references(() => promotions.id),
    promotionSnapshot: jsonb('promotion_snapshot'),
    payment: text().notNull(),
    cashGiven: numeric('cash_given', { precision: 12, scale: 2 }),
    change: numeric({ precision: 12, scale: 2 }),
    /** card | none | phone */
    vitayMode: text('vitay_mode').notNull(),
    vitayCardMasked: text('vitay_card_masked'),
    vitayTest: boolean('vitay_test').notNull().default(false),
    vitayPhoneMasked: text('vitay_phone_masked'),
    nip: text(),
    company: text(),
    status: text().notNull().default('active'),
    cancelledAt: timestamp('cancelled_at', { withTimezone: true }),
    cancelledBy: integer('cancelled_by').references(() => employees.id),
    cancelReason: text('cancel_reason'),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    index('fuelings_shift_idx').on(t.shiftId),
    index('fuelings_created_idx').on(t.createdAt),
  ],
)

export const promotions = pgTable('promotions', {
  id: serial().primaryKey(),
  title: text().notNull(),
  description: text().notNull().default(''),
  /** Empty list = every fuel. */
  fuelIds: jsonb('fuel_ids').$type<string[]>().notNull().default([]),
  /** info | per_liter | percent */
  discountType: text('discount_type').notNull().default('info'),
  discountValue: numeric('discount_value', { precision: 10, scale: 3 })
    .notNull()
    .default('0'),
  requiresVitay: boolean('requires_vitay').notNull().default(false),
  minLiters: numeric('min_liters', { precision: 10, scale: 2 }),
  conditions: text().notNull().default(''),
  validFrom: timestamp('valid_from', { withTimezone: true }).notNull(),
  validTo: timestamp('valid_to', { withTimezone: true }),
  /** draft | active | ended */
  status: text().notNull().default('draft'),
  createdBy: integer('created_by')
    .notNull()
    .references(() => employees.id),
  updatedBy: integer('updated_by').references(() => employees.id),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

/** Audit trail: created, updated, activated, ended. */
export const promotionEvents = pgTable('promotion_events', {
  id: serial().primaryKey(),
  promotionId: integer('promotion_id')
    .notNull()
    .references(() => promotions.id),
  action: text().notNull(),
  employeeId: integer('employee_id')
    .notNull()
    .references(() => employees.id),
  at: timestamp({ withTimezone: true }).notNull().defaultNow(),
})

export const announcements = pgTable('announcements', {
  id: serial().primaryKey(),
  title: text().notNull(),
  body: text().notNull(),
  /** wewnetrzny | organizacyjny | procedura | awaria | paliwowy | publiczny */
  category: text().notNull(),
  /** internal | public */
  visibility: text().notNull().default('internal'),
  important: boolean().notNull().default(false),
  /** draft | published | hidden */
  status: text().notNull().default('draft'),
  publishedAt: timestamp('published_at', { withTimezone: true }),
  expiresAt: timestamp('expires_at', { withTimezone: true }),
  authorId: integer('author_id')
    .notNull()
    .references(() => employees.id),
  updatedBy: integer('updated_by').references(() => employees.id),
  createdAt: timestamp('created_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

/** Current price per litre, set by a manager. Fills copy the price at the time of sale. */
export const fuelPrices = pgTable('fuel_prices', {
  fuelId: text('fuel_id').primaryKey(),
  price: numeric({ precision: 10, scale: 3 }).notNull(),
  updatedBy: integer('updated_by').references(() => employees.id),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})

/** Station-wide switches edited in the admin panel. */
export const stationSettings = pgTable('station_settings', {
  key: text().primaryKey(),
  value: jsonb().notNull(),
  updatedBy: integer('updated_by').references(() => employees.id),
  updatedAt: timestamp('updated_at', { withTimezone: true })
    .notNull()
    .defaultNow(),
})
